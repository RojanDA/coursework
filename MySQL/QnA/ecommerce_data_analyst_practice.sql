CREATE DATABASE IF NOT EXISTS ecommerce_data_analyst;
USE ecommerce_data_analyst;
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS payments; DROP TABLE IF EXISTS order_items; DROP TABLE IF EXISTS orders; DROP TABLE IF EXISTS products; DROP TABLE IF EXISTS customers;
SET FOREIGN_KEY_CHECKS=1;
CREATE TABLE customers(customer_id INT UNSIGNED NOT NULL, first_name VARCHAR(60) NOT NULL, last_name VARCHAR(60) NOT NULL, email VARCHAR(120) NOT NULL, city VARCHAR(60) NOT NULL, region VARCHAR(60) NOT NULL, signup_date DATE NOT NULL, gender VARCHAR(20) NULL, PRIMARY KEY(customer_id), UNIQUE KEY uq_customers_email(email)) ENGINE=InnoDB;
CREATE TABLE products(product_id INT UNSIGNED NOT NULL, product_name VARCHAR(120) NOT NULL, category VARCHAR(60) NOT NULL, list_price DECIMAL(10,2) NOT NULL, unit_cost DECIMAL(10,2) NOT NULL, active TINYINT(1) NOT NULL DEFAULT 1, PRIMARY KEY(product_id), CHECK(list_price>=0 AND unit_cost>=0)) ENGINE=InnoDB;
CREATE TABLE orders(order_id INT UNSIGNED NOT NULL, customer_id INT UNSIGNED NOT NULL, order_date DATE NOT NULL, order_status ENUM('pending','processing','shipped','delivered','cancelled') NOT NULL, subtotal DECIMAL(12,2) NOT NULL, discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0, total_amount DECIMAL(12,2) NOT NULL, PRIMARY KEY(order_id), KEY idx_orders_customer_date(customer_id,order_date), KEY idx_orders_date_status(order_date,order_status), CONSTRAINT fk_orders_customer FOREIGN KEY(customer_id) REFERENCES customers(customer_id), CHECK(subtotal>=0 AND discount_amount>=0 AND total_amount>=0 AND total_amount=subtotal-discount_amount)) ENGINE=InnoDB;
CREATE TABLE order_items(order_item_id INT UNSIGNED NOT NULL, order_id INT UNSIGNED NOT NULL, product_id INT UNSIGNED NOT NULL, quantity SMALLINT UNSIGNED NOT NULL, unit_price DECIMAL(10,2) NOT NULL, unit_cost DECIMAL(10,2) NOT NULL, discount_percent DECIMAL(5,2) NOT NULL DEFAULT 0, line_subtotal DECIMAL(12,2) NOT NULL, discount_amount DECIMAL(12,2) NOT NULL, line_revenue DECIMAL(12,2) NOT NULL, gross_profit DECIMAL(12,2) NOT NULL, PRIMARY KEY(order_item_id), UNIQUE KEY uq_order_product(order_id,product_id), KEY idx_items_product(product_id), CONSTRAINT fk_items_order FOREIGN KEY(order_id) REFERENCES orders(order_id), CONSTRAINT fk_items_product FOREIGN KEY(product_id) REFERENCES products(product_id), CHECK(quantity>0 AND discount_percent BETWEEN 0 AND 100 AND discount_amount<=line_subtotal)) ENGINE=InnoDB;
CREATE TABLE payments(payment_id INT UNSIGNED NOT NULL, order_id INT UNSIGNED NOT NULL, payment_amount DECIMAL(12,2) NOT NULL, payment_method ENUM('card','digital_wallet','bank_transfer','cash_on_delivery') NOT NULL, payment_status ENUM('pending','paid','failed','refunded') NOT NULL, payment_date DATE NULL, PRIMARY KEY(payment_id), UNIQUE KEY uq_payment_order(order_id), CONSTRAINT fk_payments_order FOREIGN KEY(order_id) REFERENCES orders(order_id), CHECK(payment_amount>=0)) ENGINE=InnoDB;
